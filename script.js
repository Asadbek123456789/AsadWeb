// MULTI-LANG LOGIKASI METODLARI
i18next.init({ lng: 'uz', resources }, function() { updateContent(); });

function updateContent() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        el.innerText = i18next.t(el.getAttribute('data-i18n'));
    });
    
    // Form placeholder'larini ham dinamik o'zgartirish
    const currentLang = i18next.language;
    if(currentLang === 'uz') {
        document.getElementById('form-name').placeholder = "Ismingiz";
        document.getElementById('form-email').placeholder = "Sizning Gmail manzilingiz";
        document.getElementById('form-msg').placeholder = "Loyiha haqida batafsil...";
    } else if(currentLang === 'en') {
        document.getElementById('form-name').placeholder = "Your Name";
        document.getElementById('form-email').placeholder = "Your Gmail Address";
        document.getElementById('form-msg').placeholder = "Detailed about project...";
    } else if(currentLang === 'ru') {
        document.getElementById('form-name').placeholder = "Ваше Имя";
        document.getElementById('form-email').placeholder = "Ваш Gmail Адрес";
        document.getElementById('form-msg').placeholder = "Подробнее о проекте...";
    }
}

// Select o'zgarganda til darhol almashadi
document.getElementById('lang-select').addEventListener('change', (e) => {
    i18next.changeLanguage(e.target.value, () => {
        updateContent();
    });
});

// GLOBAL HAMMA TOMONDAN TUSHADIGAN BARGLAR
function createPremiumLeaves() {
    const container = document.getElementById('leaves-container');
    const leafColors = ['#e67e22', '#d35400', '#f1c40f', '#e74c3c', '#ba5c12'];
    for (let i = 0; i < 35; i++) {
        let leaf = document.createElement('div');
        leaf.classList.add('leaf');
        leaf.style.left = Math.random() * 100 + 'vw';
        leaf.style.backgroundColor = leafColors[Math.floor(Math.random() * leafColors.length)];
        const scale = Math.random() * 0.6 + 0.6;
        leaf.style.transform = `scale(${scale})`;
        leaf.style.animationDuration = (Math.random() * 6 + 5) + 's';
        leaf.style.animationDelay = (Math.random() * 5) + 's';
        container.appendChild(leaf);
    }
}

// WINDOW LOAD - EXACTLY 2 SECONDS (2000ms)
window.addEventListener('load', () => {
    createPremiumLeaves();
    setTimeout(() => {
        const preloader = document.getElementById('preloader');
        preloader.classList.add('zoom-out');
        setTimeout(() => {
            preloader.style.opacity = '0';
            setTimeout(() => {
                preloader.style.display = 'none';
                document.getElementById('login-overlay').classList.remove('hidden');
            }, 400);
        }, 600);
    }, 2000); 
});

// LOGIN TUGMASI INTEGRATSIYASI VA MATRIX HUDUDIDA QOCHISH LOGIKASI
const loginBtn = document.getElementById('login-btn');
const email = document.getElementById('email');
const pass = document.getElementById('password');

document.addEventListener('mousemove', (e) => {
    if ((email.value.trim() === "" || pass.value.trim() === "") && window.innerWidth > 768) {
        const btnRect = loginBtn.getBoundingClientRect();
        const btnCenterX = btnRect.left + btnRect.width / 2;
        const btnCenterY = btnRect.top + btnRect.height / 2;
        const distance = Math.hypot(e.clientX - btnCenterX, e.clientY - btnCenterY);

        if (distance < 90) {
            const escapeX = (Math.random() - 0.5) * 360; 
            const escapeY = (Math.random() - 0.5) * 240;
            loginBtn.style.transform = `translate(${escapeX}px, ${escapeY}px)`;
        }
    }
});

function checkInputs() {
    if (email.value.trim() !== "" && pass.value.trim() !== "") {
        loginBtn.style.transform = "translate(0px, 0px)";
    }
}
email.addEventListener('input', checkInputs);
pass.addEventListener('input', checkInputs);

// ASADWEB TEPAGA QAYTISH TUGMASI LOGIKASI
const scrollTopBtn = document.getElementById('scroll-top-btn');
window.addEventListener('scroll', () => {
    if (window.scrollY > 500) {
        scrollTopBtn.classList.add('show');
    } else {
        scrollTopBtn.classList.remove('show');
    }
});
scrollTopBtn.addEventListener('click', () => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
});

// TIZIMGA KIRISH VA FONAR
const mask = document.getElementById('flashlight-mask');
let isFlashlightActive = false;

loginBtn.addEventListener('click', () => {
    if (email.value.trim() !== "" && pass.value.trim() !== "") {
        document.getElementById('login-overlay').style.opacity = "0";
        setTimeout(() => {
            document.getElementById('login-overlay').style.display = "none";
            if(window.innerWidth > 768) {
                mask.classList.remove('hidden');
                isFlashlightActive = true;
            }
            document.getElementById('main-site').classList.remove('hidden');
        }, 500);
    }
});

document.addEventListener('mousemove', (e) => {
    if(window.innerWidth > 768 && isFlashlightActive) {
        mask.style.setProperty('--x', `${e.clientX}px`);
        mask.style.setProperty('--y', `${e.clientY}px`);
    }
});

document.addEventListener('keydown', (e) => {
    if (isFlashlightActive && (e.key === 'f' || e.key === 'F')) {
        mask.classList.toggle('disabled-flash');
    }
});

